"""Provider-independent data source interface (SIH26078, Phase 6).

The whole point of this module is that **no provider is baked into the system**.
Everything downstream - normalization, quality control, the registry, the API -
talks to a :class:`WeatherDataSource` and never to a file format or a vendor.

The interface is deliberately small::

    name()      stable identifier, used in manifests and the API
    available() is this source usable right now? (never raises)
    fetch()      acquire bytes / a dataset (local, remote, cached)
    load()       return an xarray.Dataset in the *source's own* units
    metadata()  describe the source without touching the data

Why ``available()`` is separate from ``name()``: a provider can be registered and
listed while being unusable (no dependency, no credentials, no network). The
API lists sources either way, so a dashboard can show "ERA5 - configured: no"
instead of pretending the source does not exist.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Protocol, runtime_checkable

import xarray as xr

__all__ = [
    "DataOrigin",
    "SourceInfo",
    "WeatherDataSource",
    "utc_now",
]


def utc_now() -> datetime:
    """Return the current UTC time (second resolution)."""
    return datetime.now(timezone.utc).replace(microsecond=0)


class DataOrigin:
    """The three provenance classes a dataset can belong to.

    These are deliberately distinct because conflating them is the single most
    common way a demo becomes a misleading product:

    * ``SYNTHETIC`` - generated by this project. No real observation.
    * ``HISTORICAL`` - a real past period (reanalysis or archive). *Not* live.
    * ``EXTERNAL`` - a real source fetched at run time. Still not a forecast.
    """

    SYNTHETIC = "SYNTHETIC"
    HISTORICAL = "HISTORICAL"
    EXTERNAL = "EXTERNAL"

    ALL = (SYNTHETIC, HISTORICAL, EXTERNAL)

    @classmethod
    def validate(cls, value: str) -> str:
        """Normalise and validate an origin string.

        Raises:
            ValueError: If the value is not one of the three known origins.
        """
        candidate = str(value).strip().upper()
        if candidate not in cls.ALL:
            raise ValueError(
                f"Unknown data origin '{value}'. Use one of {', '.join(cls.ALL)}."
            )
        return candidate


@dataclass(frozen=True)
class SourceInfo:
    """Metadata about a registered source, returned by ``metadata()``.

    Nothing here is a measurement: it describes the *source*, so it can be listed
    without opening a file or making a network call.
    """

    name: str
    kind: str
    description: str
    formats: tuple[str, ...] = ()
    requires_credentials: bool = False
    required_environment: tuple[str, ...] = ()
    optional_dependency: str | None = None
    default_origin: str = DataOrigin.EXTERNAL
    notes: str = ""

    def as_dict(self) -> dict[str, Any]:
        """Return a JSON-serialisable dictionary (used by the API)."""
        return {
            "name": self.name,
            "kind": self.kind,
            "description": self.description,
            "formats": list(self.formats),
            "requires_credentials": self.requires_credentials,
            "required_environment": list(self.required_environment),
            "optional_dependency": self.optional_dependency,
            "default_origin": self.default_origin,
            "notes": self.notes,
        }


@runtime_checkable
class WeatherDataSource(Protocol):
    """The adapter interface every data source implements."""

    def name(self) -> str:
        """Return a stable, human-readable source identifier."""
        ...

    def available(self) -> bool:
        """Return True when this source can be used right now.

        Must never raise and must never touch the network: it answers "is this
        configured?", which is what the API's source list needs.
        """
        ...

    def fetch(self, *args: Any, **kwargs: Any) -> Path:
        """Acquire the raw data and return the local path of the source file.

        For a local file this validates and returns the path. For a remote
        provider it downloads (into a cache directory) and returns the cached
        path.

        Raises:
            SourceNotFoundError: If the requested source file does not exist.
            DataSourceUnavailableError: If a remote source is unreachable.
            ProviderCredentialsMissingError: If credentials are required.
        """
        ...

    def load(self, path: Path | str, **kwargs: Any) -> xr.Dataset:
        """Open the source file and return an :class:`xarray.Dataset`.

        The dataset is returned in the **source's own units and coordinates**;
        normalization is a separate, explicit step
        (:mod:`extreme_weather.ingestion.normalizer`) so the raw metadata always
        survives for the manifest.

        Args:
            path: Local path of the source file.
            **kwargs: Backend options, e.g. ``chunks=`` for lazy loading.

        Raises:
            IngestionError: If the file cannot be read.
            MissingDependencyError: If an optional dependency is required.
        """
        ...

    def metadata(self) -> SourceInfo:
        """Describe the source without reading any data."""
        ...

    def default_origin(self) -> str:
        """Return the :class:`DataOrigin` this source produces by default."""
        ...
